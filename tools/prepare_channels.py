#!/usr/bin/env python3
"""Prepare immutable npm metadata and a Homebrew formula from verified ZIPs."""
import argparse
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from anki_x import __version__

PLATFORMS = {"darwin-arm64": "macos-arm64", "darwin-x64": "macos-x64",
             "win32-x64": "windows-x64", "linux-x64": "linux-x64"}


def npm_version(version):
    match = re.fullmatch(r"(\d+\.\d+\.\d+)(?:(a|b|rc)(\d+))?", version)
    if not match:
        raise ValueError("Release version must be X.Y.Z or X.Y.Z{a,b,rc}N")
    base, pre, number = match.groups()
    return base + (f"-{dict(a='alpha', b='beta', rc='rc')[pre]}.{number}" if pre else "")


def prepare(assets, output, *, version=__version__, partial=False):
    npm = output / "npm"
    if npm.exists():
        shutil.rmtree(npm)
    shutil.copytree(ROOT / "packaging/npm", npm, ignore=shutil.ignore_patterns("node_modules", "test", "*.tgz"))
    for name in ("LICENSE", "THIRD_PARTY_NOTICES.md"):
        shutil.copy2(ROOT / name, npm / name)
    shutil.copy2(ROOT / "packaging/npm/README.md", npm / "README.md")
    package = json.loads((npm / "package.json").read_text())
    package["version"] = npm_version(version)
    (npm / "package.json").write_text(json.dumps(package, indent=2) + "\n")
    lockfile = npm / "package-lock.json"
    if lockfile.exists():
        lock = json.loads(lockfile.read_text())
        lock["version"] = package["version"]
        lock["packages"][""]["version"] = package["version"]
        lockfile.write_text(json.dumps(lock, indent=2) + "\n")
    manifest = {"version": version, "platforms": {}}
    for node, native in PLATFORMS.items():
        filename = f"anki-x-{version}-{native}.zip"
        archive = assets / filename
        if partial and not archive.exists():
            continue
        with archive.open("rb") as stream:
            digest = hashlib.file_digest(stream, "sha256").hexdigest()
        manifest["platforms"][node] = {"sha256": digest,
            "url": f"https://github.com/HunterChan-SR/anki-x/releases/download/v{version}/{filename}"}
    if not manifest["platforms"]:
        raise ValueError("No release archives found")
    (npm / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (npm / "bin/anki-x.cjs").chmod(0o755)
    if not partial:
        formula = output / "homebrew/Formula/anki-x.rb"
        formula.parent.mkdir(parents=True, exist_ok=True)
        formula.write_text(homebrew_formula(version, manifest["platforms"]))
    print(json.dumps({"version": version, "npm_version": package["version"],
                      "npm_tag": "next" if "-" in package["version"] else "latest"}))
    return manifest


def homebrew_formula(version, platforms):
    def block(key, indent):
        asset = platforms[key]
        return f'{indent}url "{asset["url"]}"\n{indent}sha256 "{asset["sha256"]}"\n'
    return (f'''# Generated by anki-x's release workflow. Do not edit checksums by hand.
class AnkiX < Formula
  desc "Learn with Anki Desktop from your terminal"
  homepage "https://github.com/HunterChan-SR/anki-x"
  version "{version}"
  license "MIT"

  on_macos do
    depends_on macos: :ventura
    on_arm do
''' + block("darwin-arm64", "      ") + '''    end
    on_intel do
''' + block("darwin-x64", "      ") + '''    end
  end
  on_linux do
    depends_on arch: :x86_64
''' + block("linux-x64", "    ") + '''  end

  def install
    libexec.install Dir["*"]
    chmod 0755, libexec/"anki-x"
    (bin/"anki-x").write_env_script libexec/"anki-x", ANKI_X_PACKAGE_MANAGER: "homebrew"
  end

  def caveats
    <<~EOS
      Run anki-x to set up Anki Desktop and start learning.
      Linux requires glibc 2.35 or newer. This release is unsigned.
      Update with brew upgrade; your Anki data and settings are preserved.
    EOS
  end

  test do
    ENV["ANKI_X_HOME"] = (testpath/"user").to_s
    assert_equal version.to_s, shell_output("#{bin}/anki-x --version").strip
    assert_match "brew upgrade", shell_output("#{bin}/anki-x update")
  end
end
''')


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assets", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--partial", action="store_true", help="Local single-platform smoke test only")
    args = parser.parse_args()
    prepare(args.assets, args.output, partial=args.partial)
